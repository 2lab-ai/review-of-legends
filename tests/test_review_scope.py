def _file(name: str, patch: str | None = "@@ -1,1 +1,2 @@\n context\n+added\n", **extra) -> dict:
    item = {"filename": name, "status": "modified", "additions": 1, "deletions": 0, "changes": 1}
    if patch is not None:
        item["patch"] = patch
    item.update(extra)
    return item


class GlobTest(unittest.TestCase):
    def match(self, pattern: str, path: str) -> bool:
        return bool(scope.glob_regex(pattern).fullmatch(path))

    def test_a_pattern_without_a_slash_matches_the_file_name_at_any_depth(self) -> None:
        self.assertTrue(self.match("*.md", "README.md"))
        self.assertTrue(self.match("*.md", "docs/deep/guide.md"))
        self.assertFalse(self.match("*.md", "docs/guide.mdx"))

    def test_a_pattern_with_a_slash_is_rooted_and_double_star_spans_directories(self) -> None:
        self.assertTrue(self.match("docs/**", "docs/a/b.txt"))
        self.assertFalse(self.match("docs/**", "src/docs/a.txt"))
        self.assertTrue(self.match("**/docs/**", "src/docs/a.txt"))
        self.assertFalse(self.match("src/*.py", "src/a/b.py"))
        self.assertTrue(self.match("/setup.cfg", "setup.cfg"))
        self.assertFalse(self.match("/setup.cfg", "pkg/setup.cfg"))

    def test_braces_classes_and_case(self) -> None:
        self.assertTrue(self.match("*.{yml,yaml}", "ci/a.yaml"))
        self.assertTrue(self.match("file[0-9].txt", "file7.txt"))
        self.assertFalse(self.match("file[!0-9].txt", "file7.txt"))
        self.assertTrue(self.match("*.md", "NOTES.MD"))


class DefaultScopeTest(unittest.TestCase):
    def reason(self, name: str, settings: scope.ScopeSettings = DEFAULTS, **extra) -> str | None:
        return scope.file_reason(_file(name, **extra), settings)

    def test_generated_files_are_left_out(self) -> None:
        for name in ("package-lock.json", "web/yarn.lock", "go.sum", "Cargo.lock", "static/app.min.js",
                     "api/v1/user.pb.go", "proto/user_pb2.py", "dist/index.js", "src/__snapshots__/a.snap"):
            self.assertEqual(self.reason(name), scope.GENERATED, name)

    def test_documentation_is_left_out(self) -> None:
        for name in ("README.md", "docs/guide.mdx", "CHANGELOG.md", "LICENSE", "NOTICE.txt", "docs/notes.txt",
                     "manual.rst", "spec.adoc"):
            self.assertEqual(self.reason(name), scope.DOCUMENTATION, name)

    def test_vendored_dependencies_are_left_out(self) -> None:
        for name in ("vendor/github.com/x/y.go", "web/node_modules/left-pad/index.js", "ios/Pods/A/a.m"):
            self.assertEqual(self.reason(name), scope.VENDORED, name)

    def test_code_tests_and_text_build_files_stay_in(self) -> None:
        for name in ("src/app.py", "src/dist.py", "history.py", "tests/test_app.py", "app.test.ts",
                     "requirements.txt", "CMakeLists.txt", ".github/workflows/ci.yml", "docs/conf.py",
                     ".env.example"):
            self.assertIsNone(self.reason(name), name)

    def test_secret_paths_are_left_out_and_no_include_brings_them_back(self) -> None:
        everything = scope.settings_for({"review_scope": {"include": ["**"], "exclude_categories": []}}, "a/b")
        for name in (".env", "deploy/.env.production", "id_rsa", "home/.ssh/config", "certs/server.pem",
                     ".npmrc", "a/.docker/config.json"):
            self.assertEqual(self.reason(name), scope.SECRET, name)
            self.assertEqual(self.reason(name, everything), scope.SECRET, name)

    def test_a_file_renamed_away_from_a_secret_name_is_still_secret(self) -> None:
        self.assertEqual(self.reason("settings.txt", previous_filename=".env", status="renamed"), scope.SECRET)

    def test_a_generator_header_at_the_top_marks_the_file_generated(self) -> None:
        added = "@@ -0,0 +1,3 @@\n+// Code generated by sqlc. DO NOT EDIT.\n+package db\n+\n"
        self.assertEqual(self.reason("internal/db/query.sql.go", patch=added), scope.GENERATED)
        meta = "@@ -1,2 +1,3 @@\n # @generated by tool\n+x = 1\n y = 2\n"
        self.assertEqual(self.reason("lib/schema.py", patch=meta), scope.GENERATED)

    def test_a_header_phrase_far_from_the_top_does_not(self) -> None:
        deep = "@@ -40,2 +40,3 @@\n # Code generated by x. DO NOT EDIT.\n+y = 1\n z = 2\n"
        self.assertIsNone(self.reason("lib/notes.py", patch=deep))
        later_line = "@@ -1,7 +1,8 @@\n a\n b\n c\n d\n e\n f\n+# @generated\n"
        self.assertIsNone(self.reason("lib/late.py", patch=later_line))


class SettingsTest(unittest.TestCase):
    def test_include_beats_a_category_and_exclude_beats_include(self) -> None:
        settings = scope.settings_for(
            {"review_scope": {"include": ["docs/**"], "exclude": ["docs/drafts/**", "*.sql"]}}, "a/b"
        )
        self.assertIsNone(scope.file_reason(_file("docs/api.md"), settings))
        self.assertEqual(scope.file_reason(_file("docs/drafts/x.md"), settings), scope.CONFIGURED)
        self.assertEqual(scope.file_reason(_file("db/schema.sql"), settings), scope.CONFIGURED)
        self.assertEqual(scope.file_reason(_file("README.md"), settings), scope.DOCUMENTATION)

    def test_a_repository_block_replaces_the_keys_it_sets_matched_case_insensitively(self) -> None:
        config = {"review_scope": {
            "exclude": ["*.sql"],
            "repositories": {"Acme-Corp/Docs-Site": {"exclude_categories": ["generated", "vendored"]}},
        }}
        docs_site = scope.settings_for(config, "acme-corp/docs-site")
        self.assertIsNone(scope.file_reason(_file("guide.md"), docs_site))
        self.assertEqual(scope.file_reason(_file("a.sql"), docs_site), scope.CONFIGURED)  # global key kept
        other = scope.settings_for(config, "acme-corp/app")
        self.assertEqual(scope.file_reason(_file("guide.md"), other), scope.DOCUMENTATION)

    def test_an_empty_category_list_reviews_every_non_secret_file(self) -> None:
        settings = scope.settings_for({"review_scope": {"exclude_categories": []}}, "a/b")
        self.assertIsNone(scope.file_reason(_file("README.md"), settings))
        self.assertIsNone(scope.file_reason(_file("package-lock.json"), settings))

    def test_validate_refuses_bad_shapes(self) -> None:
        for raw in (
            [],
            {"exclude_categories": ["docs"]},
            {"exclude_categories": "generated"},
            {"include": [""]},
            {"exclude": [3]},
            {"repositories": []},
            {"repositories": {"not-a-repo": {}}},
            {"repositories": {"acme-corp/app": {"include": "docs/**"}}},
        ):
            with self.assertRaises(ValueError, msg=repr(raw)):
                scope.validate({"review_scope": raw})
        scope.validate({})
        scope.validate({"review_scope": {"exclude_categories": [], "include": ["a/**"],
                                         "repositories": {"acme-corp/app": {"exclude": ["*.sql"]}}}})

    def test_load_config_refuses_a_bad_review_scope(self) -> None:
        raw = json.loads((ROOT / "config" / "reviewer.json").read_text(encoding="utf-8"))
        raw["review_scope"] = {"exclude_categories": ["everything"]}
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "reviewer.json"
            path.write_text(json.dumps(raw), encoding="utf-8")
            with self.assertRaises(svc.ServiceError) as caught:
                svc.load_config(path)
        self.assertIn("exclude_categories", str(caught.exception))

    def test_the_shipped_config_loads_and_keeps_the_default_categories(self) -> None:
        config = svc.load_config(ROOT / "config" / "reviewer.json")
        settings = scope.settings_for(config, config["repositories"][0])
        self.assertEqual(settings.exclude_categories, frozenset(scope.CATEGORIES))


class FilesNotReadTest(unittest.TestCase):
    def test_every_file_left_unread_is_named_with_its_reason(self) -> None:
        files = [
            _file("app.py"),
            _file("README.md"),
            _file("big.py", patch="@@ -1,1 +1,2 @@\n a\n+" + "x" * 500 + "\n"),
            _file("huge.sql", patch=None, additions=4000, deletions=10),
            _file("logo.png", patch=None, additions=0, deletions=0, status="added"),
            _file("moved.py", patch=None, additions=0, deletions=0, status="renamed", previous_filename="old.py"),
        ]
        selected = scope.select_files(files, DEFAULTS)
        _, shown = svc.diff_and_shown_files(list(selected.reviewed), max_chars=300)
        not_read = scope.files_not_read(selected, shown)
        self.assertEqual(not_read, [
            ("README.md", scope.DOCUMENTATION),
            ("big.py", scope.BUDGET),
            ("huge.sql", scope.NO_PATCH),
            ("logo.png", scope.BINARY),
        ])
        self.assertTrue(scope.is_partial(not_read))

    def test_left_out_by_scope_alone_is_not_partial(self) -> None:
        self.assertFalse(scope.is_partial([("README.md", scope.DOCUMENTATION), ("logo.png", scope.BINARY)]))


class PromptAndBodyTest(unittest.TestCase):
    PR = {"number": 7, "title": "t", "body": "", "base": {"ref": "main"}, "head": {"ref": "f", "sha": "abc1234567"}}

    def test_the_agent_prompt_marks_files_outside_the_diff(self) -> None:
        files = [_file("app.py"), _file("README.md")]
        prompt = svc.render_prompt("acme-corp/app", self.PR, files, "diff", "agent", not_read={"README.md": "documentation"})
        self.assertIn("- README.md (modified, +1, -0) [not in the diff below: documentation]", prompt)
        self.assertIn("- app.py (modified, +1, -0)\n", prompt)
        self.assertIn("do not report on them", prompt)
        plain = svc.render_prompt("acme-corp/app", self.PR, files, "diff", "agent")
        self.assertNotIn("not in the diff below", plain)

    def body(self, not_read, total=4) -> str:
        return svc.build_review_body(
            {"marker": svc.MARKER}, self.PR, [{"agent": "correctness", "summary": "ok"}], [], 0, "v",
            files_total=total, not_read=not_read,
        )

    def test_the_body_counts_and_lists_unread_files(self) -> None:
        body = self.body([("README.md", scope.DOCUMENTATION), ("big.py", scope.BUDGET)])
        self.assertIn("Files read in full: 2/4 (partial review)", body)
        self.assertIn("### Files this review did not read", body)
        self.assertIn("**Partial review:**", body)
        self.assertIn("- `README.md` — documentation", body)
        self.assertIn("- `big.py` — past the diff budget (max_diff_chars)", body)

    def test_a_scope_only_exclusion_is_listed_without_the_partial_warning(self) -> None:
        body = self.body([("README.md", scope.DOCUMENTATION)], total=2)
        self.assertIn("Files read in full: 1/2\n", body)
        self.assertIn("- `README.md` — documentation", body)
        self.assertNotIn("Partial review", body)

    def test_a_review_that_read_everything_has_no_section(self) -> None:
        body = self.body([], total=3)
        self.assertIn("Files read in full: 3/3\n", body)
        self.assertNotIn("did not read", body)

    def test_a_long_list_is_cut_but_counted(self) -> None:
        body = self.body([(f"docs/p{i}.md", scope.DOCUMENTATION) for i in range(80)], total=81)
        self.assertIn("Files read in full: 1/81", body)
        self.assertIn("- …and 30 more", body)


class _Client:
    repo = "acme-corp/app"

    def __init__(self, files: list[dict]) -> None:
        self.files = files
        self.reviews: list[tuple[str, list]] = []
        self.statuses: list[tuple[str, str, str]] = []

    def bot_login(self):
        return "review-of-legends-bot"

    def list_files(self, number):
        return self.files

    def create_review(self, number, commit_id, body, comments, event="COMMENT"):
        self.reviews.append((body, comments))
        return {"id": 1}

    def upsert_issue_comment(self, number, marker, body):
        return {"id": 2}

    def create_commit_status(self, sha, state, description, target_url="", context=""):
        self.statuses.append((context, state, description))


class ReviewPrScopeTest(unittest.TestCase):
    def run_review(self, files: list[dict], max_diff_chars: int = 180000,
                   findings: list[dict] | None = None) -> tuple[_Client, list[dict]]:
        seen: list[dict] = []
        if findings is None:
            findings = [
                {"path": "README.md", "line": 2, "priority": 2, "title": "[P2] docs", "body": "b"},
                {"path": "app.py", "line": 2, "priority": 2, "title": "[P2] code", "body": "b"},
            ]

        def fake_run_agent(agent, config, config_dir, run_dir, repo, pr, files, diff_text, *args, **kwargs):
            seen.append({"files": files, "diff": diff_text, "not_read": kwargs.get("not_read")})
            return {"agent": agent["id"], "summary": "ok", "findings": [dict(item) for item in findings]}

        client = _Client(files)
        with tempfile.TemporaryDirectory() as tmp:
            config = {
                "agents": [{"id": "correctness", "enabled": True, "prompt_path": "../agents/correctness.md"}],
                "agent_runner": {"command": ["true"]},
                "min_successful_agents": 0,
                "max_review_comments": 30,
                "max_diff_chars": max_diff_chars,
                "work_dir": str(Path(tmp) / "work"),
                "progress_comment": {"enabled": False},
                "executive_summary": {"enabled": False},
                "visual_outline": {"enabled": False},
            }
            pr = {"number": 5, "head": {"sha": "abcdef1234567890"}, "base": {"ref": "main"},
                  "title": "t", "body": "", "user": {"login": "someone"}}
            with mock.patch.object(svc, "clone_pr_source", lambda *a, **k: None), \
                    mock.patch.object(svc, "run_agent", fake_run_agent):
                svc.review_pr(client, config, ROOT / "config" / "reviewer.json", pr, {"reviewed": {}})
        return client, seen

    def test_documentation_is_kept_out_of_the_diff_and_the_line_comments(self) -> None:
        client, seen = self.run_review([_file("app.py"), _file("README.md")])
        self.assertIn("diff --git a/app.py", seen[0]["diff"])
        self.assertNotIn("README.md", seen[0]["diff"])
        self.assertEqual(seen[0]["not_read"], {"README.md": scope.DOCUMENTATION})
        self.assertEqual([item["filename"] for item in seen[0]["files"]], ["app.py", "README.md"])
        body, comments = client.reviews[0]
        self.assertEqual([comment["path"] for comment in comments], ["app.py"])
        self.assertIn("Files read in full: 1/2", body)
        self.assertIn("- `README.md` — documentation", body)
        reviewed = [s for s in client.statuses if s[0].startswith(svc.REVIEWED_STATUS_CONTEXT)]
        self.assertEqual(reviewed[0][1:], ("success", "reviewed (abcdef123456)"))

    def test_a_cut_diff_makes_the_review_and_its_status_partial(self) -> None:
        files = [_file("app.py"), _file("big.py", patch="@@ -1,1 +1,2 @@\n a\n+" + "x" * 900 + "\n")]
        client, seen = self.run_review(files, max_diff_chars=400)
        self.assertEqual(seen[0]["not_read"], {"big.py": scope.BUDGET})
        body, _ = client.reviews[0]
        self.assertIn("Files read in full: 1/2 (partial review)", body)
        reviewed = [s for s in client.statuses if s[0].startswith(svc.REVIEWED_STATUS_CONTEXT)]
        self.assertEqual(reviewed[0][2], "reviewed (abcdef123456); partial: 1 of 2 files not read")

    def test_a_secret_file_never_reaches_an_agent(self) -> None:
        secret = _file(".env", patch="@@ -0,0 +1,1 @@\n+API_KEY=sk-live-123\n")
        client, seen = self.run_review([_file("app.py"), secret])
        self.assertNotIn("sk-live-123", seen[0]["diff"])
        self.assertEqual(seen[0]["not_read"], {".env": scope.SECRET})
        self.assertIn("- `.env` — secret path, left out of every prompt", client.reviews[0][0])

    def test_a_file_github_sent_without_a_patch_alone_makes_the_review_partial(self) -> None:
        client, seen = self.run_review([_file("app.py"), _file("huge.sql", patch=None, additions=5000)])
        self.assertEqual(seen[0]["not_read"], {"huge.sql": scope.NO_PATCH})
        body, _ = client.reviews[0]
        self.assertIn("Files read in full: 1/2 (partial review)", body)
        self.assertIn("**Partial review:**", body)
        reviewed = [s for s in client.statuses if s[0].startswith(svc.REVIEWED_STATUS_CONTEXT)]
        self.assertEqual(reviewed[0][2], "reviewed (abcdef123456); partial: 1 of 2 files not read")

    def test_the_prompt_written_for_the_runner_carries_no_secret_patch(self) -> None:
        # The real run_agent: the prompt file the runner reads is what the model gets.
        files = [_file("app.py"), _file(".env", patch="@@ -0,0 +1,1 @@\n+API_KEY=sk-live-123\n"),
                 _file("cfg.txt", patch="@@ -1,1 +1,1 @@\n-A=1\n+TOKEN=sk-live-456\n",
                       previous_filename="id_rsa", status="renamed")]
        client = _Client(files)
        reply = json.dumps({"summary": "ok", "findings": []})
        with tempfile.TemporaryDirectory() as tmp:
            config = {
                "agents": [{"id": "correctness", "enabled": True, "prompt_path": "../agents/correctness.md"}],
                "agent_runner": {"command": ["/bin/sh", "-c", 'printf "%s" "$1" > "$0"', "{response_file}", reply]},
                "min_successful_agents": 0,
                "max_review_comments": 30,
                "work_dir": str(Path(tmp) / "work"),
                "progress_comment": {"enabled": False},
                "executive_summary": {"enabled": False},
                "visual_outline": {"enabled": False},
            }
            pr = {"number": 6, "head": {"sha": "abcdef1234567890"}, "base": {"ref": "main"},
                  "title": "t", "body": "", "user": {"login": "someone"}}
            with mock.patch.object(svc, "clone_pr_source", lambda *a, **k: None):
                svc.review_pr(client, config, ROOT / "config" / "reviewer.json", pr, {"reviewed": {}})
            prompts = list((Path(tmp) / "work").rglob("correctness.prompt.md"))
            self.assertEqual(len(prompts), 1)
